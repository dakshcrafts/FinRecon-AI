from datetime import datetime, timezone
import enum
from sqlalchemy import Column, Integer, String, Float, DateTime, Text, ForeignKey, Boolean
from sqlalchemy.orm import relationship
from app.database import Base

class MatchStatus(str, enum.Enum):
    PROPOSED = "PROPOSED"                   # Generated by reconciliation engine, awaiting review/auto-approval
    APPROVED = "APPROVED"                   # Formally approved and balances updated
    REJECTED = "REJECTED"                   # Discarded by reviewer
    MANUAL_ALLOCATED = "MANUAL_ALLOCATED"   # Manually paired by user/analyst

class ConfidenceTier(str, enum.Enum):
    HIGH = "HIGH"               # Score >= Auto-match threshold (e.g. 85)
    MEDIUM = "MEDIUM"           # Review queue threshold (60-84)
    LOW = "LOW"                 # < Review queue threshold (< 60)
    SUSPICIOUS = "SUSPICIOUS"   # Flags (duplicate candidate, overpayment, suspicious)

class ReconciliationMatch(Base):
    __tablename__ = "reconciliation_matches"

    id = Column(Integer, primary_key=True, index=True)
    invoice_id = Column(Integer, ForeignKey("invoices.id", ondelete="CASCADE"), nullable=False, index=True)
    payment_id = Column(Integer, ForeignKey("payments.id", ondelete="CASCADE"), nullable=False, index=True)
    
    allocated_amount = Column(Float, nullable=False)
    confidence_score = Column(Float, nullable=False)
    confidence_tier = Column(String(20), default=ConfidenceTier.MEDIUM.value, nullable=False)
    status = Column(String(30), default=MatchStatus.PROPOSED.value, index=True, nullable=False)
    
    strategy_applied = Column(String(100), nullable=False)
    explanation = Column(Text, nullable=False)
    match_details = Column(Text, nullable=True)  # JSON-encoded score breakdown & metrics
    
    approved_by_user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    approved_at = Column(DateTime, nullable=True)
    rejected_by_user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    rejected_at = Column(DateTime, nullable=True)
    rejection_reason = Column(Text, nullable=True)

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc), nullable=False)

    invoice = relationship("Invoice", back_populates="matches")
    payment = relationship("Payment", back_populates="matches")
    approved_by_user = relationship("User", foreign_keys=[approved_by_user_id])
    rejected_by_user = relationship("User", foreign_keys=[rejected_by_user_id])

class ReconciliationSetting(Base):
    __tablename__ = "reconciliation_settings"

    id = Column(Integer, primary_key=True)
    weight_invoice_number = Column(Float, default=40.0, nullable=False)
    weight_customer_name = Column(Float, default=25.0, nullable=False)
    weight_amount = Column(Float, default=20.0, nullable=False)
    weight_date_proximity = Column(Float, default=15.0, nullable=False)
    
    auto_match_threshold = Column(Float, default=85.0, nullable=False)
    review_queue_threshold = Column(Float, default=60.0, nullable=False)
    ambiguity_margin = Column(Float, default=5.0, nullable=False)
    auto_match_enabled = Column(Boolean, default=True, nullable=False)
    date_tolerance_days = Column(Integer, default=30, nullable=False)
    
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc), nullable=False)
